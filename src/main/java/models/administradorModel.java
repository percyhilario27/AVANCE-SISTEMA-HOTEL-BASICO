package models;

/**
 *
 * @author olivera
 */
public class administradorModel extends usuarioModel {

    private int idAdmin;
    private String codGestion;

    public administradorModel() {
    }

    public administradorModel(int idAdmin, String codGestion, int idUsuario, String email, String password, String rol, String authProvider, String nombres, String apellidos) {
        super(idUsuario, email, password, rol, authProvider, nombres, apellidos);
        this.idAdmin = idAdmin;
        this.codGestion = codGestion;
    }

    public int getIdAdmin() {
        return idAdmin;
    }

    public void setIdAdmin(int idAdmin) {
        this.idAdmin = idAdmin;
    }

    public String getCodGestion() {
        return codGestion;
    }

    public void setCodGestion(String codGestion) {
        this.codGestion = codGestion;
    }

    public int getIdUsuario() {
        return idUsuario;
    }

    public void setIdUsuario(int idUsuario) {
        this.idUsuario = idUsuario;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getRol() {
        return rol;
    }

    public void setRol(String rol) {
        this.rol = rol;
    }

    public String getAuthProvider() {
        return authProvider;
    }

    public void setAuthProvider(String authProvider) {
        this.authProvider = authProvider;
    }

    public String getNombres() {
        return nombres;
    }

    public void setNombres(String nombres) {
        this.nombres = nombres;
    }

    public String getApellidos() {
        return apellidos;
    }

    public void setApellidos(String apellidos) {
        this.apellidos = apellidos;
    }

    
   
}
